"""Identify a hidden mechanical teacher from its V0 sensor via local EP."""
import argparse
import json
from pathlib import Path
import time
import torch
from hdr_motor_ai.mechanics import GearNetwork
from hdr_motor_ai.local_learning import local_update, predict_local


def evaluate(seed=2,epochs=40,lr=1.0,beta=.5,steps=300,output='results/v04/calibration'):
    torch.manual_seed(seed)
    torch.set_num_threads(2)
    teacher=GearNetwork(channels=1)
    with torch.no_grad():
        idx=torch.tensor([k in ('group','hub') for k in teacher.edge_kinds],dtype=torch.bool)
        teacher.log_k[idx,0] += torch.randn(int(idx.sum()))*.9
        teacher.ratio_logits[idx,0] += torch.randn(int(idx.sum()))*.8
    student=GearNetwork(channels=1)
    g=torch.Generator().manual_seed(seed+31)
    xtr=torch.rand(512,6,generator=g)*2-1
    xval=torch.rand(256,6,generator=g)*2-1
    xte=torch.rand(512,6,generator=g)*2-1
    with torch.no_grad():
        ytr=predict_local(teacher,xtr,steps)
        yval=predict_local(teacher,xval,steps)
        yte=predict_local(teacher,xte,steps)
    def mse(x,y):return float(((predict_local(student,x,steps)-y)**2).mean())
    baseline=mse(xte,yte); best_val=float('inf');best_weights=None
    track=[]; start=time.monotonic()
    for epoch in range(epochs):
        ix=torch.randperm(len(xtr))
        for j in range(0,len(ix),64):
            b=ix[j:j+64]
            local_update(student,xtr[b],torch.zeros(len(b)),teacher_angles=ytr[b],
                         free_steps=steps,nudged_steps=steps,beta=beta,lr=lr,
                         train_kinds=('group','hub'),train_ratios=True)
        val=mse(xval,yval); track.append(val)
        if val < best_val:
            best_val=val;best_weights={k:v.clone() for k,v in student.state_dict().items()}
        if epoch%10==0 or epoch==epochs-1:print(f'calibration epoch {epoch+1}: val_mse={val:.7f}',flush=True)
    student.load_state_dict(best_weights)
    test=mse(xte,yte)
    out={'version':'0.4.0','study':'supervised mechanical V0 system identification',
         'seed':seed,'epochs':epochs,'steps_per_phase':steps,'lr':lr,'beta':beta,
         'test_mse_untrained':baseline,'validation_mse_best':best_val,'test_mse_learned':test,
         'test_mse_improvement_pct':100*(baseline-test)/baseline,
         'seconds':round(time.monotonic()-start,3),
         'caveat':'Train/validation/test inputs held out. Teacher data generated by another synthetic mechanical model, not hardware.'}
    p=Path(output);p.mkdir(parents=True,exist_ok=True)
    (p/'summary.json').write_text(json.dumps(out,indent=2))
    (p/'val_mse.json').write_text(json.dumps(track,indent=2))
    (p/'learned_gears.json').write_text(json.dumps(student.browser_export(),indent=2))
    print(json.dumps(out,indent=2),flush=True)
    return out

if __name__=='__main__':
    p=argparse.ArgumentParser()
    p.add_argument('--seed',type=int,default=2);p.add_argument('--epochs',type=int,default=40)
    p.add_argument('--lr',type=float,default=1.0);p.add_argument('--beta',type=float,default=.5)
    p.add_argument('--steps',type=int,default=300);p.add_argument('--output',default='results/v04/calibration')
    a=p.parse_args(); evaluate(a.seed,a.epochs,a.lr,a.beta,a.steps,a.output)
